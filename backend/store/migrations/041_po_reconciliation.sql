-- 041_po_reconciliation: live header reconciliation sessions (#502, ticket 04).
--
-- A reconciliation session is the retained record of one PO against one exact
-- source revision. A never-linked draft has no session and no invented source.
-- Linking (or creating from a Quotation) creates one active session for the
-- exact revision; draft saves retain it; reopen returns the same IDs, mappings
-- and history. Finalize makes the session read-only. A source repair (ticket
-- 06) will deactivate the old session and install a new one; this migration
-- only provides the generation column and the uniqueness that makes a return
-- to a previously used revision possible.
--
-- # Uniqueness (R-06)
--
-- UNIQUE (purchase_order_id, source_quotation_id, source_revision, generation)
-- lets a repair back to a previously used revision insert a new generation
-- instead of colliding with the retained history. At most one session is
-- active per PO (partial unique index on purchase_order_id WHERE active),
-- which also means at most one active per PO/source pair.
--
-- # Source revision reference
--
-- source_quotation_id + source_revision are the immutable link (the revision
-- number 0 is real, never "no source"). source_revision_id is the exact
-- quotation_revisions row when it still exists; it is SET NULL on source
-- deletion so old sessions stay readable (R-07: pre-041 records have no
-- session at all, and no backfill invents one).
--
-- # Immutability
--
-- A session attached to a saved record cannot be edited through the
-- draft-session writer. The BEFORE UPDATE triggers below enforce it even for
-- a hand-written statement: a readonly session refuses every update, and a
-- session whose PO is saved refuses every update. Finalize updates the session
-- to readonly BEFORE it flips the PO to saved, so the allowed transition is
-- never blocked by its own guard. DELETEs are left to the FK cascade so
-- whole-chain PO deletion (#480) still removes its sessions; direct deletes
-- of readonly/saved sessions are refused.
--
-- # Values
--
-- Item values are JSONB because one slot carries text, integers (quantity
-- x10_000, money minor units, whole-PO percent), Discount {Enabled, Percent}
-- and TaxBasis triples, or null for missing-source slots. History is a JSONB
-- array, oldest-first, of recorded reference/state/value changes with their
-- original actor and time. Line identities are a JSONB array on the session:
-- [{Key, ID, Removed}], where Key is `id:<row>` for a persisted line or
-- `client:<UUID>` for an editor line, ID is null before the first save, and
-- Removed marks a deleted line whose history is retained.
--
-- Money stays integer minor units; no float enters these columns (AGENTS.md
-- section 10). All amounts that cross to the desktop are bounded to
-- 2^53-1 by the Go validators; these CHECKs are the backstop for kind, status
-- and key shape only.

CREATE TABLE IF NOT EXISTS {{schema}}.purchase_order_reconciliation_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id UUID NOT NULL REFERENCES {{schema}}.organizations(id),
    purchase_order_id BIGINT NOT NULL
        REFERENCES {{schema}}.purchase_orders(id) ON DELETE CASCADE,
    source_quotation_id BIGINT NOT NULL,
    source_revision SMALLINT NOT NULL CHECK (source_revision >= 0),
    source_revision_id BIGINT NULL
        REFERENCES {{schema}}.quotation_revisions(id) ON DELETE SET NULL,
    generation INTEGER NOT NULL CHECK (generation >= 1),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    readonly BOOLEAN NOT NULL DEFAULT FALSE,
    po_version BIGINT NOT NULL CHECK (po_version > 0),
    line_identities JSONB NOT NULL DEFAULT '[]',
    created_by BIGINT NOT NULL REFERENCES {{schema}}.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (purchase_order_id, source_quotation_id, source_revision, generation),
    CHECK (jsonb_typeof(line_identities) = 'array')
);

CREATE UNIQUE INDEX IF NOT EXISTS purchase_order_reconciliation_active_idx
    ON {{schema}}.purchase_order_reconciliation_sessions (purchase_order_id)
    WHERE active;

CREATE INDEX IF NOT EXISTS purchase_order_reconciliation_org_idx
    ON {{schema}}.purchase_order_reconciliation_sessions (org_id, purchase_order_id);

CREATE INDEX IF NOT EXISTS purchase_order_reconciliation_source_idx
    ON {{schema}}.purchase_order_reconciliation_sessions
        (org_id, source_quotation_id, source_revision);

CREATE TABLE IF NOT EXISTS {{schema}}.purchase_order_reconciliation_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id UUID NOT NULL REFERENCES {{schema}}.organizations(id),
    session_id BIGINT NOT NULL
        REFERENCES {{schema}}.purchase_order_reconciliation_sessions(id) ON DELETE CASCADE,
    purchase_order_id BIGINT NOT NULL
        REFERENCES {{schema}}.purchase_orders(id) ON DELETE CASCADE,
    key TEXT NOT NULL CHECK (char_length(key) BETWEEN 1 AND 200),
    field TEXT NOT NULL CHECK (char_length(field) BETWEEN 1 AND 80),
    kind TEXT NOT NULL
        CHECK (kind IN ('difference', 'missing_line', 'extra_line', 'duplicate_match', 'tax_basis')),
    line_key TEXT NULL CHECK (line_key IS NULL OR char_length(line_key) BETWEEN 1 AND 120),
    source_line_ref TEXT NULL CHECK (source_line_ref IS NULL OR char_length(source_line_ref) BETWEEN 1 AND 40),
    label TEXT NOT NULL CHECK (char_length(label) BETWEEN 1 AND 200),
    po_value JSONB NULL,
    source_value JSONB NULL,
    status TEXT NOT NULL CHECK (status IN ('unresolved', 'resolved')),
    resolution TEXT NULL
        CHECK (resolution IN ('kept_po', 'used_quotation', 'values_now_match', 'acknowledged_missing', 'acknowledged_extra', 'match_corrected', 'line_removed')),
    actor_id BIGINT NOT NULL REFERENCES {{schema}}.users(id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    history JSONB NOT NULL DEFAULT '[]',
    UNIQUE (session_id, key),
    CHECK (jsonb_typeof(history) = 'array'),
    CHECK ((status = 'resolved') = (resolution IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS purchase_order_reconciliation_items_session_idx
    ON {{schema}}.purchase_order_reconciliation_items (org_id, session_id);

CREATE INDEX IF NOT EXISTS purchase_order_reconciliation_items_po_idx
    ON {{schema}}.purchase_order_reconciliation_items (org_id, purchase_order_id);

-- Immutability guards. They raise 23514 so a hand-written UPDATE fails the
-- same way a CHECK violation does. Cascade deletes bypass the DELETE guard
-- because the parent PO row is already gone when it fires.

CREATE OR REPLACE FUNCTION {{schema}}.purchase_order_reconciliation_session_guard()
RETURNS trigger
LANGUAGE plpgsql
AS $reconciliation_guard$
DECLARE
    po_state TEXT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        -- Whole-chain PO deletion cascades here after the parent row is
        -- gone; that is the only delete path that may remove a session.
        SELECT state INTO po_state FROM {{schema}}.purchase_orders WHERE id = OLD.purchase_order_id;
        IF NOT FOUND THEN
            RETURN OLD;
        END IF;
        IF OLD.readonly THEN
            RAISE EXCEPTION
                'purchase order reconciliation session % is read-only; it cannot be deleted',
                OLD.id
                USING ERRCODE = '23514';
        END IF;
        IF po_state = 'saved' THEN
            RAISE EXCEPTION
                'purchase order % is saved; its reconciliation session % cannot be deleted',
                OLD.purchase_order_id, OLD.id
                USING ERRCODE = '23514';
        END IF;
        RETURN OLD;
    END IF;
    IF OLD.readonly THEN
        -- Source deletion nulls source_revision_id via ON DELETE SET NULL.
        -- That FK maintenance is the only update a read-only session allows;
        -- every user edit stays refused.
        IF NEW.source_revision_id IS DISTINCT FROM OLD.source_revision_id
           AND NEW.org_id IS NOT DISTINCT FROM OLD.org_id
           AND NEW.purchase_order_id IS NOT DISTINCT FROM OLD.purchase_order_id
           AND NEW.source_quotation_id IS NOT DISTINCT FROM OLD.source_quotation_id
           AND NEW.source_revision IS NOT DISTINCT FROM OLD.source_revision
           AND NEW.generation IS NOT DISTINCT FROM OLD.generation
           AND NEW.active IS NOT DISTINCT FROM OLD.active
           AND NEW.readonly IS NOT DISTINCT FROM OLD.readonly
           AND NEW.po_version IS NOT DISTINCT FROM OLD.po_version
           AND NEW.line_identities IS NOT DISTINCT FROM OLD.line_identities
           AND NEW.created_by IS NOT DISTINCT FROM OLD.created_by
           AND NEW.created_at IS NOT DISTINCT FROM OLD.created_at THEN
            NEW.updated_at := NOW();
            RETURN NEW;
        END IF;
        RAISE EXCEPTION
            'purchase order reconciliation session % is read-only; record a new session instead',
            OLD.id
            USING ERRCODE = '23514';
    END IF;
    SELECT state INTO po_state FROM {{schema}}.purchase_orders WHERE id = OLD.purchase_order_id;
    IF FOUND AND po_state = 'saved' THEN
        -- Same FK maintenance allowance for sessions of saved records.
        IF NEW.source_revision_id IS DISTINCT FROM OLD.source_revision_id
           AND NEW.org_id IS NOT DISTINCT FROM OLD.org_id
           AND NEW.purchase_order_id IS NOT DISTINCT FROM OLD.purchase_order_id
           AND NEW.source_quotation_id IS NOT DISTINCT FROM OLD.source_quotation_id
           AND NEW.source_revision IS NOT DISTINCT FROM OLD.source_revision
           AND NEW.generation IS NOT DISTINCT FROM OLD.generation
           AND NEW.active IS NOT DISTINCT FROM OLD.active
           AND NEW.readonly IS NOT DISTINCT FROM OLD.readonly
           AND NEW.po_version IS NOT DISTINCT FROM OLD.po_version
           AND NEW.line_identities IS NOT DISTINCT FROM OLD.line_identities
           AND NEW.created_by IS NOT DISTINCT FROM OLD.created_by
           AND NEW.created_at IS NOT DISTINCT FROM OLD.created_at THEN
            NEW.updated_at := NOW();
            RETURN NEW;
        END IF;
        RAISE EXCEPTION
            'purchase order % is saved; its reconciliation session % is immutable',
            OLD.purchase_order_id, OLD.id
            USING ERRCODE = '23514';
    END IF;
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$reconciliation_guard$;

DROP TRIGGER IF EXISTS purchase_order_reconciliation_sessions_guard_trigger
    ON {{schema}}.purchase_order_reconciliation_sessions;
CREATE TRIGGER purchase_order_reconciliation_sessions_guard_trigger
    BEFORE UPDATE OR DELETE ON {{schema}}.purchase_order_reconciliation_sessions
    FOR EACH ROW
    EXECUTE FUNCTION {{schema}}.purchase_order_reconciliation_session_guard();

CREATE OR REPLACE FUNCTION {{schema}}.purchase_order_reconciliation_item_guard()
RETURNS trigger
LANGUAGE plpgsql
AS $reconciliation_item_guard$
DECLARE
    session_readonly BOOLEAN;
    session_found BOOLEAN;
    po_state TEXT;
    po_found BOOLEAN;
BEGIN
    IF TG_OP = 'DELETE' THEN
        SELECT s.readonly INTO session_readonly
        FROM {{schema}}.purchase_order_reconciliation_sessions s WHERE s.id = OLD.session_id;
        session_found := FOUND;
        SELECT state INTO po_state FROM {{schema}}.purchase_orders WHERE id = OLD.purchase_order_id;
        po_found := FOUND;
        -- Cascade from a deleted PO or session arrives after its parent is
        -- gone; that is the only delete path that may remove an item.
        IF NOT po_found THEN
            RETURN OLD;
        END IF;
        IF session_found AND session_readonly THEN
            RAISE EXCEPTION
                'purchase order reconciliation item % is read-only; it cannot be deleted',
                OLD.id
                USING ERRCODE = '23514';
        END IF;
        IF po_state = 'saved' THEN
            RAISE EXCEPTION
                'purchase order % is saved; its reconciliation item % cannot be deleted',
                OLD.purchase_order_id, OLD.id
                USING ERRCODE = '23514';
        END IF;
        RETURN OLD;
    END IF;
    SELECT s.readonly INTO session_readonly
    FROM {{schema}}.purchase_order_reconciliation_sessions s WHERE s.id = OLD.session_id;
    IF FOUND AND session_readonly THEN
        RAISE EXCEPTION
            'purchase order reconciliation item % is read-only; record a new decision instead',
            OLD.id
            USING ERRCODE = '23514';
    END IF;
    SELECT state INTO po_state FROM {{schema}}.purchase_orders WHERE id = OLD.purchase_order_id;
    IF FOUND AND po_state = 'saved' THEN
        RAISE EXCEPTION
            'purchase order % is saved; its reconciliation item % is immutable',
            OLD.purchase_order_id, OLD.id
            USING ERRCODE = '23514';
    END IF;
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$reconciliation_item_guard$;

DROP TRIGGER IF EXISTS purchase_order_reconciliation_items_guard_trigger
    ON {{schema}}.purchase_order_reconciliation_items;
CREATE TRIGGER purchase_order_reconciliation_items_guard_trigger
    BEFORE UPDATE OR DELETE ON {{schema}}.purchase_order_reconciliation_items
    FOR EACH ROW
    EXECUTE FUNCTION {{schema}}.purchase_order_reconciliation_item_guard();

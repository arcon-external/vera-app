-- 033_purchase_order_documents: the single optional customer PO PDF (#472).
--
-- A purchase order carries at most one *active* original PDF. It is evidence,
-- not a second PO: uploading, replacing or removing a document never writes a
-- purchase-order column (except the final save's deliberate no-PDF
-- confirmation), and the bytes are stored exactly as uploaded.
--
-- # One active document, versioned history
--
-- Every upload inserts a new row with the next version number and marks the
-- previous active row as replaced. Rows are never updated in place and their
-- bytes are never rewritten, so the earlier evidence stays inspectable. An
-- explicit removal marks the active row removed and leaves the row (and its
-- bytes) in place as history; #480's whole-chain deletion is the only operation
-- that removes document rows.
--
-- The partial unique index below is the invariant, not a convention: at most
-- one row per purchase order may have active = TRUE. It makes a code path that
-- forgets to swap the pointer fail loudly instead of leaving two current PDFs.
--
-- # Race and deletion-safety contract
--
-- 1. Attach and remove both begin a transaction, lock the owning
--    purchase_orders row with SELECT ... FOR UPDATE inside the caller's
--    organization, then change the active pointer and insert the next version.
--    Two concurrent replacements therefore serialize: one wins version N, the
--    next wins N+1, and exactly one row remains active. UNIQUE
--    (purchase_order_id, version) is the backstop against a duplicate version
--    if that lock is ever removed.
-- 2. The active-pointer swap and the new version's insert commit together. A
--    failed upload leaves the previous active document untouched; there is no
--    window in which a PO has zero current documents because a replacement
--    partially applied.
-- 3. Every read joins purchase_orders and filters po.org_id, so a document
--    cannot be fetched, version-listed or removed across the organization
--    boundary even by guessing a sequential id.
-- 4. Removal retains the row, its bytes and its metadata (removed_at,
--    removed_by) as correction history. Retrieval by version still serves it.
-- 5. Deleting a purchase order cascades its document rows. The bytes live in
--    Postgres, so that deletion is one transactional operation with no
--    external file to clean up. If a later ticket moves document bytes to
--    object storage, it must add a retryable cleanup record in the same
--    transaction rather than describing cross-system deletion as atomic.
--
-- # Why no supporting-attachment collection
--
-- The parent specification allows one optional customer PO PDF and explicitly
-- excludes a collection of supporting files. This table has no category,
-- title or ordinal: a row is a version of the one document, not an attachment
-- item. The parent row is the purchase order.

CREATE TABLE IF NOT EXISTS {{schema}}.purchase_order_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    org_id UUID NOT NULL REFERENCES {{schema}}.organizations(id),
    purchase_order_id BIGINT NOT NULL
        REFERENCES {{schema}}.purchase_orders(id) ON DELETE CASCADE,
    -- Monotonic per purchase order. Never reused, even after a removal: the
    -- next upload is version N+1 so history keeps a stable address.
    version INTEGER NOT NULL CHECK (version > 0),
    -- The original file, byte for byte. No normalization, no re-render.
    pdf_data BYTEA NOT NULL CHECK (octet_length(pdf_data) > 0),
    -- Lower-case hex SHA-256 of pdf_data, computed by the store before insert.
    sha256 TEXT NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    -- The same bound the Go validator and API enforce (20 MiB). Keeping it in
    -- the schema means no alternate writer can bypass the request bound.
    size_bytes BIGINT NOT NULL
        CHECK (size_bytes > 0 AND size_bytes <= 20971520),
    -- Only PDFs are stored; the validator proves the bytes, this column keeps
    -- the response/content-type contract from drifting.
    content_type TEXT NOT NULL DEFAULT 'application/pdf'
        CHECK (content_type = 'application/pdf'),
    -- Display name only (base name, control characters removed). Never used
    -- as a filesystem path.
    original_filename TEXT NOT NULL DEFAULT ''
        CHECK (char_length(original_filename) <= 255),
    uploaded_by BIGINT NOT NULL REFERENCES {{schema}}.users(id),
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- The one current document for this PO.
    active BOOLEAN NOT NULL DEFAULT TRUE,
    -- Exactly one lifecycle marker on an inactive row:
    --   replaced_at set           -> a newer upload superseded it
    --   removed_at/removed_by set -> a staff member deliberately removed it
    replaced_at TIMESTAMPTZ NULL,
    removed_at TIMESTAMPTZ NULL,
    removed_by BIGINT NULL REFERENCES {{schema}}.users(id),
    UNIQUE (purchase_order_id, version),
    CHECK (octet_length(pdf_data) = size_bytes),
    CHECK (
        (active
         AND replaced_at IS NULL
         AND removed_at IS NULL
         AND removed_by IS NULL)
        OR
        (NOT active
         AND ((replaced_at IS NOT NULL) <> (removed_at IS NOT NULL))
         AND ((removed_at IS NULL) = (removed_by IS NULL)))
    )
);

-- The active-pointer invariant. Partial so history rows do not collide.
CREATE UNIQUE INDEX IF NOT EXISTS purchase_order_documents_active_idx
    ON {{schema}}.purchase_order_documents (purchase_order_id)
    WHERE active;

-- History is read newest-first inside an organization; this keeps the scoped
-- lookup indexed even after a record accumulates correction versions.
CREATE INDEX IF NOT EXISTS purchase_order_documents_org_history_idx
    ON {{schema}}.purchase_order_documents (org_id, purchase_order_id, version DESC);

CREATE TABLE IF NOT EXISTS {{schema}}.customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code SMALLINT NOT NULL UNIQUE,
    legal_name TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS {{schema}}.customer_addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES {{schema}}.customers(id) ON DELETE CASCADE,
    address TEXT NOT NULL,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS customer_primary_address_idx
    ON {{schema}}.customer_addresses (customer_id)
    WHERE is_primary = TRUE;

CREATE TABLE IF NOT EXISTS {{schema}}.tax_rates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tax_zone TEXT NOT NULL,
    tax_category TEXT NOT NULL DEFAULT '',
    rate_bps SMALLINT NOT NULL CHECK (rate_bps >= 0 AND rate_bps <= 10000),
    UNIQUE (tax_zone, tax_category)
);


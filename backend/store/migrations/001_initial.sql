CREATE TABLE IF NOT EXISTS {{schema}}.sequence_counters (
    name TEXT PRIMARY KEY,
    next_value BIGINT NOT NULL CHECK (next_value >= 1)
);

CREATE TABLE IF NOT EXISTS {{schema}}.quotations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_number TEXT NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES {{schema}}.customers(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS {{schema}}.quotation_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_id BIGINT NOT NULL REFERENCES {{schema}}.quotations(id) ON DELETE CASCADE,
    revision_number SMALLINT NOT NULL CHECK (revision_number >= 0),
    recipient_name TEXT NOT NULL,
    recipient_address TEXT NOT NULL,
    subject TEXT NOT NULL,
    incoterm TEXT NOT NULL,
    validity_days SMALLINT NOT NULL CHECK (validity_days > 0),
    payment_term_days SMALLINT NOT NULL CHECK (payment_term_days > 0),
    lead_time_days SMALLINT NOT NULL CHECK (lead_time_days > 0),
    discount_percent SMALLINT NOT NULL CHECK (discount_percent BETWEEN 0 AND 100),
    tax_zone TEXT NOT NULL,
    tax_category TEXT NOT NULL DEFAULT '',
    tax_rate_bps SMALLINT NOT NULL CHECK (tax_rate_bps BETWEEN 0 AND 10000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (quotation_id, revision_number)
);

CREATE TABLE IF NOT EXISTS {{schema}}.quotation_revision_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_id BIGINT NOT NULL REFERENCES {{schema}}.quotation_revisions(id) ON DELETE CASCADE,
    item_no INTEGER NOT NULL CHECK (item_no > 0),
    description TEXT NOT NULL,
    qty BIGINT NOT NULL CHECK (qty > 0),
    uom TEXT NOT NULL,
    unit_price BIGINT NOT NULL CHECK (unit_price >= 0),
    margin_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    margin_percent SMALLINT NOT NULL CHECK (margin_percent BETWEEN 0 AND 100),
    margin_amount BIGINT NOT NULL CHECK (margin_amount >= 0),
    original_total BIGINT NOT NULL CHECK (original_total >= 0),
    marginalized_unit_price BIGINT NOT NULL CHECK (marginalized_unit_price >= 0),
    marginalized_total BIGINT NOT NULL CHECK (marginalized_total >= 0),
    UNIQUE (revision_id, item_no)
);

CREATE TABLE IF NOT EXISTS {{schema}}.quotation_revision_totals (
    revision_id BIGINT PRIMARY KEY REFERENCES {{schema}}.quotation_revisions(id) ON DELETE CASCADE,
    original_subtotal BIGINT NOT NULL CHECK (original_subtotal >= 0),
    original_discount BIGINT NOT NULL CHECK (original_discount >= 0),
    original_grand_total BIGINT NOT NULL CHECK (original_grand_total >= 0),
    marginalized_subtotal BIGINT NOT NULL CHECK (marginalized_subtotal >= 0),
    marginalized_discount BIGINT NOT NULL CHECK (marginalized_discount >= 0),
    marginalized_grand_total BIGINT NOT NULL CHECK (marginalized_grand_total >= 0),
    tax_amount BIGINT NOT NULL CHECK (tax_amount >= 0),
    marginalized_grand_after_tax BIGINT NOT NULL CHECK (marginalized_grand_after_tax >= 0),
    profit_amount BIGINT NOT NULL,
    nett_profit BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS {{schema}}.quotation_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_id BIGINT NOT NULL UNIQUE REFERENCES {{schema}}.quotation_revisions(id) ON DELETE CASCADE,
    html_snapshot TEXT NOT NULL,
    pdf_data BYTEA,
    pdf_path TEXT,
    sha256 TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (pdf_data IS NOT NULL OR pdf_path IS NOT NULL)
);

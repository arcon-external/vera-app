-- 017: sub-sub-items.
--
-- A priced sub-item can spell out what it includes with detail lines. They
-- carry no values of their own -- no quantity, no cost, no margin -- so the
-- table is description and ordering only: the money stays on the sub-item the
-- detail lines belong to.
--
-- Keyed to the sub-item row the same way sub-items key to revision items:
-- revisions are immutable, so a detail line is part of the snapshot and never
-- rewritten. sub_sub_no orders the lines within one sub-item (1..N), unique
-- per parent.

CREATE TABLE IF NOT EXISTS {{schema}}.quotation_revision_sub_sub_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_sub_item_id BIGINT NOT NULL REFERENCES {{schema}}.quotation_revision_sub_items(id) ON DELETE CASCADE,
    sub_sub_no INTEGER NOT NULL CHECK (sub_sub_no > 0),
    description TEXT NOT NULL,
    UNIQUE (revision_sub_item_id, sub_sub_no)
);

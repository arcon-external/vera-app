-- 016: priced sub-items.
--
-- A quotation line can be a package of parts, each priced on its own, with the
-- line's price being the sum of the parts. One row per sub-item, keyed to the
-- revision item it belongs to: revisions are immutable, so a sub-item is part
-- of a revision's snapshot exactly as the parent line is.
--
-- Money columns mirror quotation_revision_items: BIGINT rupiah, integer only.
-- The margin constraint is the widened range from 015 (a sub-item can carry the
-- same margin a line can). unit_price is the sell (marginalized) unit price;
-- unit_cost is the cost side, shown for internal transparency only.
--
-- sub_no orders the parts within a package (1..N, edit history reorders
-- freely), unique per revision item.

CREATE TABLE IF NOT EXISTS {{schema}}.quotation_revision_sub_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_item_id BIGINT NOT NULL REFERENCES {{schema}}.quotation_revision_items(id) ON DELETE CASCADE,
    sub_no INTEGER NOT NULL CHECK (sub_no > 0),
    description TEXT NOT NULL,
    qty BIGINT NOT NULL CHECK (qty > 0),
    uom TEXT NOT NULL,
    unit_cost BIGINT NOT NULL CHECK (unit_cost >= 0),
    margin_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    margin_percent SMALLINT NOT NULL CHECK (margin_percent BETWEEN 0 AND 1000),
    unit_price BIGINT NOT NULL CHECK (unit_price >= 0),
    margin_amount BIGINT NOT NULL CHECK (margin_amount >= 0),
    total BIGINT NOT NULL CHECK (total >= 0),
    UNIQUE (revision_item_id, sub_no)
);

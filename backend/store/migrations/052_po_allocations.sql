-- 052_po_allocations: the canonical link from a purchase-order line to the
-- exact quotation revision item or sub-item it fulfils (parent #648, #650).
--
-- The allocation is the cost identity the report has been missing. A PO line
-- keeps its customer-facing description, quantity, UoM and negotiated price;
-- the allocation records the source quantity, the frozen quotation price
-- baseline, the actual PO revenue and the frozen supplier cost. A null
-- reference remains a legacy line: no allocation is invented from a
-- description or a position.
--
-- One PO line owns exactly one allocation. A quotation item may appear in many
-- POs, but only once inside one PO. The composite foreign keys make a line
-- from another PO impossible to attach here.

CREATE UNIQUE INDEX IF NOT EXISTS purchase_order_items_id_po_uidx
    ON {{schema}}.purchase_order_items (id, purchase_order_id);

CREATE TABLE IF NOT EXISTS {{schema}}.purchase_order_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id UUID NOT NULL REFERENCES {{schema}}.organizations(id),
    purchase_order_id BIGINT NOT NULL,
    purchase_order_item_id BIGINT NOT NULL,
    quotation_id BIGINT NOT NULL CHECK (quotation_id > 0),
    source_revision SMALLINT NOT NULL CHECK (source_revision >= 0),
    -- The exact revision row while it exists. A source deletion clears only
    -- this pointer (Postgres 15 column-list SET NULL); the quotation id,
    -- revision number, revenue and cost snapshot stay readable.
    source_revision_id BIGINT NULL,
    quotation_item_no INTEGER NOT NULL CHECK (quotation_item_no > 0),
    quotation_sub_no INTEGER NULL CHECK (quotation_sub_no IS NULL OR quotation_sub_no > 0),
    -- Quantity with four decimal places, the same scale as the PO line.
    quantity_scaled BIGINT NOT NULL CHECK (
        quantity_scaled BETWEEN 1 AND 9007199254740991),
    source_uom TEXT NOT NULL DEFAULT '',
    ordered_uom TEXT NOT NULL DEFAULT '',
    -- The frozen row-discounted quotation unit price: the baseline for price
    -- variance and for the delivery-price comparison. Never a supplier cost.
    quoted_unit_price_minor BIGINT NOT NULL CHECK (
        quoted_unit_price_minor BETWEEN 0 AND 9007199254740991),
    -- The actual PO line revenue at its negotiated quantity and price.
    revenue_minor BIGINT NOT NULL CHECK (
        revenue_minor BETWEEN 0 AND 9007199254740991),
    -- The exact supplier unit cost from the pinned revision. Nullable only for
    -- a legacy source whose revision row was already deleted.
    cost_unit_minor BIGINT NULL CHECK (
        cost_unit_minor IS NULL OR cost_unit_minor BETWEEN 0 AND 9007199254740991),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (purchase_order_item_id, purchase_order_id)
        REFERENCES {{schema}}.purchase_order_items (id, purchase_order_id)
        ON DELETE CASCADE,
    FOREIGN KEY (purchase_order_id, org_id)
        REFERENCES {{schema}}.purchase_orders (id, org_id)
        ON DELETE CASCADE,
    FOREIGN KEY (source_revision_id, quotation_id, source_revision)
        REFERENCES {{schema}}.quotation_revisions (id, quotation_id, revision_number)
        ON DELETE SET NULL (source_revision_id)
);

-- One allocation per quotation-backed PO line.
CREATE UNIQUE INDEX IF NOT EXISTS po_allocations_item_uidx
    ON {{schema}}.purchase_order_allocations (purchase_order_item_id);

-- One source leaf per PO. A quotation item may sit in many POs, but a single
-- PO cannot list the same source twice.
CREATE UNIQUE INDEX IF NOT EXISTS po_allocations_po_source_uidx
    ON {{schema}}.purchase_order_allocations
        (purchase_order_id, quotation_item_no, quotation_sub_no)
    NULLS NOT DISTINCT;

CREATE INDEX IF NOT EXISTS po_allocations_org_po_idx
    ON {{schema}}.purchase_order_allocations
        (org_id, purchase_order_id, purchase_order_item_id);

CREATE INDEX IF NOT EXISTS po_allocations_org_quotation_item_idx
    ON {{schema}}.purchase_order_allocations
        (org_id, quotation_id, quotation_item_no, quotation_sub_no)
    INCLUDE (purchase_order_id, source_revision, quantity_scaled,
             quoted_unit_price_minor, revenue_minor, cost_unit_minor);

-- A correction keeps the old allocation picture beside the old line picture.
-- The snapshot has no foreign key to the live allocation: the live row may be
-- replaced or deleted, while the audit copy must remain readable.
CREATE TABLE IF NOT EXISTS {{schema}}.purchase_order_correction_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correction_id BIGINT NOT NULL
        REFERENCES {{schema}}.purchase_order_corrections(id) ON DELETE CASCADE,
    line_number INTEGER NOT NULL CHECK (line_number > 0),
    quotation_id BIGINT NOT NULL CHECK (quotation_id > 0),
    source_revision SMALLINT NOT NULL CHECK (source_revision >= 0),
    source_revision_id BIGINT NULL,
    quotation_item_no INTEGER NOT NULL CHECK (quotation_item_no > 0),
    quotation_sub_no INTEGER NULL CHECK (quotation_sub_no IS NULL OR quotation_sub_no > 0),
    quantity_scaled BIGINT NOT NULL CHECK (quantity_scaled > 0),
    source_uom TEXT NOT NULL DEFAULT '',
    ordered_uom TEXT NOT NULL DEFAULT '',
    quoted_unit_price_minor BIGINT NOT NULL CHECK (quoted_unit_price_minor >= 0),
    revenue_minor BIGINT NOT NULL CHECK (revenue_minor >= 0),
    cost_unit_minor BIGINT NULL CHECK (cost_unit_minor IS NULL OR cost_unit_minor >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS purchase_order_correction_allocations_correction_idx
    ON {{schema}}.purchase_order_correction_allocations (correction_id);

-- Provable historical backfill. Only lines that already carry a quotation
-- reference are touched; a null reference stays legacy and uncosted. The
-- historical PO line net is the revenue, never a re-priced quotation amount.
INSERT INTO {{schema}}.purchase_order_allocations (
    org_id, purchase_order_id, purchase_order_item_id,
    quotation_id, source_revision, source_revision_id,
    quotation_item_no, quotation_sub_no,
    quantity_scaled, source_uom, ordered_uom,
    quoted_unit_price_minor, revenue_minor, cost_unit_minor
)
SELECT
    po.org_id, po.id, poi.id,
    po.quotation_id, po.source_revision, rev.id,
    poi.quotation_item_no, poi.quotation_sub_no,
    poi.quantity_scaled,
    COALESCE(sub.uom, qi.uom, poi.uom),
    poi.uom,
    COALESCE(
        CASE WHEN poi.quotation_sub_no IS NULL
             THEN qi.marginalized_unit_price
             ELSE sub.unit_price
        END,
        poi.unit_price_minor
    ),
    poi.net_minor,
    CASE WHEN poi.quotation_sub_no IS NULL THEN qi.unit_price ELSE sub.unit_cost END
FROM {{schema}}.purchase_order_items poi
JOIN {{schema}}.purchase_orders po ON po.id = poi.purchase_order_id
LEFT JOIN {{schema}}.quotation_revisions rev
       ON rev.quotation_id = po.quotation_id
      AND rev.revision_number = po.source_revision
      AND rev.currency = po.currency
LEFT JOIN {{schema}}.quotation_revision_items qi
       ON qi.revision_id = rev.id
      AND qi.item_no = poi.quotation_item_no
LEFT JOIN {{schema}}.quotation_revision_sub_items sub
       ON sub.revision_item_id = qi.id
      AND sub.sub_no = poi.quotation_sub_no
WHERE po.quotation_id IS NOT NULL
  AND poi.quotation_item_no IS NOT NULL
-- Deterministic conflict resolution: if a historical PO repeats a source leaf,
-- the lowest line number keeps the allocation instead of whichever heap row the
-- scan happened to reach first.
ORDER BY po.id, poi.line_number
ON CONFLICT DO NOTHING;

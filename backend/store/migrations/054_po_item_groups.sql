-- 054_po_item_groups: the fourth, PO-only aggregate presentation layer
-- (parent #648, #654).
--
-- An aggregate PO line is one customer-facing group over one or more existing
-- priced lines of any quotation depth. It is presentation only: the header owns
-- a title, a display quantity, a display unit and a print toggle, and its total
-- is derived from the children. The children remain the priced truth and keep
-- their own description, quantity, unit, price, depth and allocation.
--
-- # One level, by construction
--
-- There is no parent-group column, and the child membership foreign key points
-- at purchase_order_items, not at another group. An aggregate therefore cannot
-- contain an aggregate: the schema has nowhere to say so.
--
-- # Cross-PO attachment is refused by the database
--
-- The membership key is (aggregate_group_id, purchase_order_id), so a line of
-- purchase order B can only name a group that carries B's own id. Raw SQL
-- cannot move a child onto another record's group.
--
-- # A separate table, not a parent row in purchase_order_items
--
-- Every row in purchase_order_items stays a real priced leaf, so the subtotal,
-- PPN, grand total, allocations, the report, reconciliation and the bought-state
-- read need no "skip the fake header" rule. A self-referencing price-less row
-- would need a line-kind filter in every consumer, and one missed filter double
-- counts or zeroes a line.
--
-- No data is backfilled. Grouping is staff intent, exactly like an allocation:
-- every existing line reads as ungrouped.

CREATE TABLE IF NOT EXISTS {{schema}}.purchase_order_item_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id UUID NOT NULL REFERENCES {{schema}}.organizations(id),
    purchase_order_id BIGINT NOT NULL,
    -- The first child's line_number. Derived by the store, never submitted.
    display_order INTEGER NOT NULL CHECK (display_order > 0),
    title TEXT NOT NULL
        CHECK (char_length(title) BETWEEN 1 AND 500 AND btrim(title) <> ''),
    -- Display quantity only: 10^4 scale, default 1. It is not an allocation.
    ordered_quantity_scaled BIGINT NOT NULL DEFAULT 10000
        CHECK (ordered_quantity_scaled BETWEEN 1 AND 9007199254740991),
    -- Display unit only: a label. No conversion.
    ordered_uom TEXT NOT NULL DEFAULT 'Lot'
        CHECK (char_length(ordered_uom) BETWEEN 1 AND 80 AND btrim(ordered_uom) <> ''),
    -- Safe default: the customer sees the title only.
    show_children_to_customer BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- Needed by the composite foreign key from purchase_order_items.
    UNIQUE (id, purchase_order_id),
    UNIQUE (purchase_order_id, display_order),
    CONSTRAINT purchase_order_item_groups_po_fkey
        FOREIGN KEY (purchase_order_id, org_id)
        REFERENCES {{schema}}.purchase_orders (id, org_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS purchase_order_item_groups_po_idx
    ON {{schema}}.purchase_order_item_groups (purchase_order_id, display_order);

ALTER TABLE {{schema}}.purchase_order_items
    ADD COLUMN IF NOT EXISTS aggregate_group_id BIGINT NULL;

-- NOT VALID + VALIDATE keeps the ACCESS EXCLUSIVE window short on a large items
-- table; every existing row is NULL, so validation is cheap.
ALTER TABLE {{schema}}.purchase_order_items
    ADD CONSTRAINT purchase_order_items_aggregate_group_fkey
    FOREIGN KEY (aggregate_group_id, purchase_order_id)
    REFERENCES {{schema}}.purchase_order_item_groups (id, purchase_order_id)
    ON DELETE SET NULL (aggregate_group_id)
    NOT VALID;

ALTER TABLE {{schema}}.purchase_order_items
    VALIDATE CONSTRAINT purchase_order_items_aggregate_group_fkey;

-- The group read joins children by (purchase_order_id, aggregate_group_id).
CREATE INDEX IF NOT EXISTS purchase_order_items_aggregate_group_idx
    ON {{schema}}.purchase_order_items (purchase_order_id, aggregate_group_id)
    WHERE aggregate_group_id IS NOT NULL;

-- Corrections already snapshot lines and allocations. The group header and the
-- child membership belong to that same evidence, so a correction history can
-- say which lines were grouped before the correction.
CREATE TABLE IF NOT EXISTS {{schema}}.purchase_order_correction_item_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correction_id BIGINT NOT NULL
        REFERENCES {{schema}}.purchase_order_corrections(id) ON DELETE CASCADE,
    display_order INTEGER NOT NULL CHECK (display_order > 0),
    title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 500 AND btrim(title) <> ''),
    ordered_quantity_scaled BIGINT NOT NULL CHECK (ordered_quantity_scaled > 0),
    ordered_uom TEXT NOT NULL CHECK (char_length(ordered_uom) BETWEEN 1 AND 80 AND btrim(ordered_uom) <> ''),
    show_children_to_customer BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (correction_id, display_order)
);

ALTER TABLE {{schema}}.purchase_order_correction_items
    ADD COLUMN IF NOT EXISTS aggregate_group_order INTEGER NULL;

-- The composite key proves a snapshot line never names a group missing from the
-- same snapshot. Group ids are not stable across saves, so the snapshot is
-- keyed by display_order -- the value the live read derives from the children.
ALTER TABLE {{schema}}.purchase_order_correction_items
    ADD CONSTRAINT purchase_order_correction_items_group_fkey
    FOREIGN KEY (correction_id, aggregate_group_order)
    REFERENCES {{schema}}.purchase_order_correction_item_groups (correction_id, display_order)
    NOT VALID;

ALTER TABLE {{schema}}.purchase_order_correction_items
    VALIDATE CONSTRAINT purchase_order_correction_items_group_fkey;

-- Snapshots are evidence: no writer may rewrite a snapshot group.
DROP TRIGGER IF EXISTS purchase_order_correction_item_groups_immutable_trigger
    ON {{schema}}.purchase_order_correction_item_groups;
CREATE TRIGGER purchase_order_correction_item_groups_immutable_trigger
    BEFORE UPDATE ON {{schema}}.purchase_order_correction_item_groups
    FOR EACH ROW
    EXECUTE FUNCTION {{schema}}.purchase_order_corrections_immutable();

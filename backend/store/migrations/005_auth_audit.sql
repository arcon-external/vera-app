CREATE TABLE IF NOT EXISTS {{schema}}.auth_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT REFERENCES {{schema}}.users(id) ON DELETE SET NULL,
    action TEXT NOT NULL,
    target_user_id BIGINT REFERENCES {{schema}}.users(id) ON DELETE SET NULL,
    details TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS auth_audit_actor_idx
    ON {{schema}}.auth_audit (actor_id, created_at DESC);

CREATE TABLE IF NOT EXISTS {{schema}}.deletion_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES {{schema}}.users(id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    decided_at TIMESTAMPTZ,
    decided_by BIGINT REFERENCES {{schema}}.users(id) ON DELETE SET NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS deletion_requests_pending_unique
    ON {{schema}}.deletion_requests (user_id)
    WHERE status = 'pending';

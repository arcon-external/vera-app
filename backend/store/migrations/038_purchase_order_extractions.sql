-- 038_purchase_order_extractions: text-PDF extraction runs (#477).
--
-- A run is bound to one *generation* of the one customer PO PDF: the document
-- row, its version and its SHA-256. It is evidence about that exact file, so a
-- replaced or removed PDF makes every result computed from the old file stale,
-- not merely older. The store discards the result when it marks a run stale;
-- a review panel must never offer proposals that belong to a different file.
--
-- # One current run per purchase order
--
-- The partial unique index permits at most one queued/running run per record.
-- Starting extraction twice for the same document is idempotent at the store
-- layer (it returns the active run), and a run bound to an older generation is
-- marked stale before a new one is inserted. The index is the backstop if a
-- code path ever forgets that rule.
--
-- # History is cheap and useful
--
-- Succeeded and failed rows stay, so a later reviewer can see what the engine
-- read and which version produced it. The API exposes only the latest run;
-- #479's retry/conflict work may expose more without a migration.
--
-- # Restart
--
-- A server restart cannot resume a subprocess. Startup recovery marks every
-- queued/running row failed with error_code = 'interrupted', so no row can
-- remain "running" for a worker that no longer exists.
--
-- # Bounds
--
-- result is JSONB because the extraction contract is a typed document, not a
-- relational table; page_count and the error fields are columns because the
-- list/latest query needs them without decoding the JSON. Every result is
-- bounded by the server's output cap before it reaches this table.

CREATE TABLE IF NOT EXISTS {{schema}}.purchase_order_extractions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    org_id UUID NOT NULL REFERENCES {{schema}}.organizations(id),
    purchase_order_id BIGINT NOT NULL
        REFERENCES {{schema}}.purchase_orders(id) ON DELETE CASCADE,
    -- The exact document generation this result describes. The foreign key
    -- cascades when whole-chain deletion removes the document rows.
    document_id BIGINT NOT NULL
        REFERENCES {{schema}}.purchase_order_documents(id) ON DELETE CASCADE,
    document_version INTEGER NOT NULL CHECK (document_version > 0),
    document_sha256 TEXT NOT NULL CHECK (document_sha256 ~ '^[0-9a-f]{64}$'),
    status TEXT NOT NULL
        CHECK (status IN ('queued', 'running', 'succeeded', 'failed', 'stale')),
    engine TEXT NOT NULL DEFAULT '',
    engine_version TEXT NOT NULL DEFAULT '',
    page_count INTEGER NOT NULL DEFAULT 0 CHECK (page_count >= 0),
    result JSONB NULL,
    error_code TEXT NULL,
    error_message TEXT NULL,
    requested_by BIGINT NOT NULL REFERENCES {{schema}}.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    started_at TIMESTAMPTZ NULL,
    finished_at TIMESTAMPTZ NULL,
    duration_ms BIGINT NULL CHECK (duration_ms IS NULL OR duration_ms >= 0),
    -- A successful run has a result and its engine identity; every other
    -- status has no result, so a stale or failed row cannot be rendered as a
    -- proposal by a reader that forgot to check the status.
    CHECK ((status = 'succeeded') = (result IS NOT NULL)),
    CHECK (status <> 'succeeded' OR (engine <> '' AND engine_version <> '' AND page_count > 0)),
    CHECK (status NOT IN ('failed', 'stale') OR error_code IS NOT NULL),
    CHECK (status IN ('queued', 'running') OR finished_at IS NOT NULL),
    CHECK (status = 'queued' OR started_at IS NOT NULL),
    CHECK (status IN ('queued', 'running') OR duration_ms IS NOT NULL)
);

-- One active run per purchase order. History rows do not collide.
CREATE UNIQUE INDEX IF NOT EXISTS purchase_order_extractions_active_idx
    ON {{schema}}.purchase_order_extractions (purchase_order_id)
    WHERE status IN ('queued', 'running');

-- The latest-run read and the retained history are both org-scoped.
CREATE INDEX IF NOT EXISTS purchase_order_extractions_latest_idx
    ON {{schema}}.purchase_order_extractions
        (org_id, purchase_order_id, created_at DESC, id DESC);

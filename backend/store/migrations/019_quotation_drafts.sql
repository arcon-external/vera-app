-- 019: private quotation drafts.
--
-- A draft is editor state that has been saved but never exported. It is
-- deliberately NOT a quotation: nothing here reserves a quote number, is
-- signed, priced, revisioned, or reachable from the verification portal. The
-- only relationship is ownership.
--
-- user_id is the whole access model. Every read, update and delete is scoped
-- by it in SQL rather than in a handler, so a handler that forgets the scope
-- cannot hand one person another person's draft -- including for an admin,
-- who has no more reach here than anyone else.
--
-- payload is the editor input verbatim as JSONB. A draft is a scratchpad and
-- is never validated on save (Prepare validates properly on export), so
-- storing the shape rather than typed columns is what lets an in-progress
-- quotation be saved while it is still unpriceable. The remaining columns
-- exist only so the drafts list can be rendered without decoding every row;
-- they are denormalised copies for display and are never read back as truth.
--
-- ON DELETE CASCADE because a draft dies with the account that wrote it.
-- Account deletion is a soft delete (users.is_active = FALSE), so the
-- DecideDeletion transaction deletes drafts explicitly; the cascade is the
-- backstop for a hard delete.

CREATE TABLE IF NOT EXISTS {{schema}}.quotation_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES {{schema}}.users(id) ON DELETE CASCADE,
    label TEXT NOT NULL DEFAULT '',
    subject TEXT NOT NULL DEFAULT '',
    customer_name TEXT NOT NULL DEFAULT '',
    customer_id BIGINT,
    item_count INTEGER NOT NULL DEFAULT 0 CHECK (item_count >= 0),
    payload JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- The list is always "mine, newest first", so the index carries the sort.
CREATE INDEX IF NOT EXISTS quotation_drafts_owner_idx
    ON {{schema}}.quotation_drafts (user_id, updated_at DESC);
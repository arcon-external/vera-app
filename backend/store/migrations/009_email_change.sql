-- 009_email_change: staff email-change requests with admin approval.
-- Mirrors deletion_requests: one pending row per user, decided rows kept
-- for history. Admins change emails directly (no request row needed).
CREATE TABLE IF NOT EXISTS {{schema}}.email_change_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES {{schema}}.users(id) ON DELETE CASCADE,
    proposed_email TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    decided_at TIMESTAMPTZ,
    decided_by BIGINT REFERENCES {{schema}}.users(id) ON DELETE SET NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS email_change_requests_pending_unique
    ON {{schema}}.email_change_requests (user_id)
    WHERE status = 'pending';

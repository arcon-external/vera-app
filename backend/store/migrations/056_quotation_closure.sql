-- 056_quotation_closure: explicit quotation closure (issue #656).
--
-- An open quotation keeps its unbought remainder as Unsold: pipeline, never a
-- loss and never subtracted from the realized variance. Closing moves that
-- remainder to Closed Loss, which is a realized loss; reopening restores Unsold.
--
-- The three live columns are cleared by a reopen, so who/when/why would be lost
-- at exactly the moment the history matters. quotation_closure_events keeps one
-- append-only row per close and per reopen, and is never rewritten.
--
-- The CHECK is the database's own guard: a closed row names a live actor and a
-- non-blank reason, an open row names neither. A reason of only spaces is
-- refused here; tabs and newlines are the store's TrimSpace check, because
-- btrim() only strips spaces.
ALTER TABLE {{schema}}.quotations
    ADD COLUMN IF NOT EXISTS closed_at TIMESTAMPTZ NULL,
    ADD COLUMN IF NOT EXISTS closed_by BIGINT NULL REFERENCES {{schema}}.users(id),
    ADD COLUMN IF NOT EXISTS closed_reason TEXT NOT NULL DEFAULT '';

ALTER TABLE {{schema}}.quotations
    ADD CONSTRAINT quotations_closure_complete
    CHECK (
        (closed_at IS NULL AND closed_by IS NULL AND closed_reason = '')
        OR (closed_at IS NOT NULL AND closed_by IS NOT NULL
            AND btrim(closed_reason) <> '')
    );

-- A closed quotation's actor is part of its current state, so closed_by is
-- restrictive: an ex-employee who still holds a closed quotation is reopened
-- first (the same rule purchase_orders.created_by already imposes).
-- The audit rows follow the existing audit-table convention instead: the event
-- survives a user deletion and only its actor reference goes null.
CREATE TABLE IF NOT EXISTS {{schema}}.quotation_closure_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_id BIGINT NOT NULL REFERENCES {{schema}}.quotations(id) ON DELETE CASCADE,
    action TEXT NOT NULL CHECK (action IN ('close', 'reopen')),
    reason TEXT NOT NULL DEFAULT '',
    actor_id BIGINT REFERENCES {{schema}}.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS quotation_closure_events_quotation_idx
    ON {{schema}}.quotation_closure_events (quotation_id, id);

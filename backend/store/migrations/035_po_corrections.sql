-- 035_po_corrections: traceable corrections and recoverable overwrites
-- (issue #473).
--
-- A saved Purchase Order is not immutable evidence like a Quotation revision;
-- staff must be able to correct a typo or a changed commercial term. What must
-- never happen is a silent rewrite: every correction keeps the exact values it
-- replaced, who replaced them, when, and why, and every write moves the record
-- to the next version so two editors cannot overwrite each other by accident.
--
-- # One monotonic version, bumped by the row
--
-- `version` starts at 1 and is bumped by a BEFORE UPDATE trigger on every write
-- to the row -- draft save, final save, correction, even the #474 confirmation
-- assignment. The trigger is the contract rather than a convention: a future
-- writer (#475's source-link repair, for instance) cannot forget to bump it,
-- and a stale `expectedVersion` therefore always names a real conflict.
--
-- # Snapshots are immutable
--
-- A correction snapshot is the record as it stood *before* the write: header
-- values, every line, and the customer PO PDF version that was active at that
-- moment. It is written in the same transaction as the correction, so a failed
-- correction leaves neither a changed record nor a snapshot. The UPDATE trigger
-- below refuses any later rewrite of a snapshot; #480's whole-chain deletion
-- (which removes the purchase order itself) is the only operation allowed to
-- remove one, through the foreign key's cascade.
--
-- # Attachment reference
--
-- The reference is the document table's (purchase_order_id, version) pair plus
-- the sha256 and display filename that version carried. Document rows are never
-- rewritten in place and a version is never reused, so the pair keeps pointing
-- at the exact bytes the record was corrected against. No foreign key is added:
-- #480 deletes the document chain with the order, while the snapshot's job is
-- to record which version was current, not to keep the bytes alive on its own.

ALTER TABLE {{schema}}.purchase_orders
    ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 1
        CHECK (version > 0);

-- Any UPDATE of the row moves it forward exactly one version. Assigning the
-- column is not how a writer bumps it; the trigger is, so NEW.version is
-- overwritten even if a caller tried to keep the old value.
CREATE OR REPLACE FUNCTION {{schema}}.purchase_orders_bump_version()
RETURNS trigger
LANGUAGE plpgsql
AS $version_guard$
BEGIN
    NEW.version := OLD.version + 1;
    RETURN NEW;
END;
$version_guard$;

DROP TRIGGER IF EXISTS purchase_orders_bump_version_trigger
    ON {{schema}}.purchase_orders;
CREATE TRIGGER purchase_orders_bump_version_trigger
    BEFORE UPDATE ON {{schema}}.purchase_orders
    FOR EACH ROW
    EXECUTE FUNCTION {{schema}}.purchase_orders_bump_version();

CREATE TABLE IF NOT EXISTS {{schema}}.purchase_order_corrections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    org_id UUID NOT NULL REFERENCES {{schema}}.organizations(id),
    purchase_order_id BIGINT NOT NULL
        REFERENCES {{schema}}.purchase_orders(id) ON DELETE CASCADE,
    -- The version this snapshot replaces, and the version the correction
    -- produced. One snapshot per replaced version: a version cannot be
    -- overwritten twice.
    previous_version BIGINT NOT NULL CHECK (previous_version > 0),
    resulting_version BIGINT NOT NULL
        CHECK (resulting_version = previous_version + 1),
    -- correction       a staff correction of a saved record, reason required
    -- draft_overwrite  the recoverable prior draft an explicit overwrite kept
    kind TEXT NOT NULL CHECK (kind IN ('correction', 'draft_overwrite')),
    -- The record's state when the snapshot was taken.
    state TEXT NOT NULL CHECK (state IN ('draft', 'saved')),
    -- The staff member's own words. Never empty, bounded to the same 500
    -- Unicode characters as the free-text payment terms, because it is shown
    -- in the history panel rather than kept as an internal note.
    reason TEXT NOT NULL
        CHECK (char_length(reason) BETWEEN 1 AND 500 AND btrim(reason) <> ''),
    actor BIGINT NOT NULL REFERENCES {{schema}}.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- The source link and the customer snapshot, exactly as they stood. The
    -- link is copied rather than joined because #475 may repair it later; a
    -- history row must keep saying what the corrected version followed.
    quotation_id BIGINT NOT NULL,
    source_revision SMALLINT NOT NULL CHECK (source_revision >= 0),
    quote_number TEXT NOT NULL DEFAULT '',
    customer_id BIGINT NOT NULL,
    customer_name TEXT NOT NULL DEFAULT '',
    currency TEXT NOT NULL,
    tax_zone TEXT NOT NULL DEFAULT '',
    tax_category TEXT NOT NULL DEFAULT '',
    -- Header values as entered.
    billing_address TEXT NOT NULL DEFAULT '',
    delivery_address TEXT NOT NULL DEFAULT '',
    ship_to_code TEXT NOT NULL DEFAULT '',
    contact_email TEXT NOT NULL DEFAULT '',
    contact_phone TEXT NOT NULL DEFAULT '',
    po_number TEXT NULL,
    po_date DATE NULL,
    received_date DATE NOT NULL,
    requested_delivery_date DATE NULL,
    payment_terms TEXT NOT NULL DEFAULT ''
        CHECK (char_length(payment_terms) <= 500),
    incoterms TEXT NOT NULL DEFAULT '',
    discount_percent SMALLINT NOT NULL DEFAULT 0
        CHECK (discount_percent BETWEEN 0 AND 100),
    -- The stored calculation as it stood, not a recalculation of these values
    -- by a later calculator.
    subtotal_minor BIGINT NOT NULL DEFAULT 0 CHECK (subtotal_minor >= 0),
    discount_minor BIGINT NOT NULL DEFAULT 0 CHECK (discount_minor >= 0),
    ppn_bps SMALLINT NOT NULL DEFAULT 0 CHECK (ppn_bps BETWEEN 0 AND 10000),
    ppn_minor BIGINT NOT NULL DEFAULT 0 CHECK (ppn_minor >= 0),
    adjustment_minor BIGINT NOT NULL DEFAULT 0,
    adjustment_reason TEXT NOT NULL DEFAULT ''
        CHECK (char_length(adjustment_reason) <= 200),
    grand_total_minor BIGINT NOT NULL DEFAULT 0 CHECK (grand_total_minor >= 0),
    -- The customer PO PDF version that was active when the snapshot was taken.
    -- Null together when there was no attachment.
    attachment_version INTEGER NULL CHECK (attachment_version > 0),
    attachment_sha256 TEXT NULL CHECK (attachment_sha256 ~ '^[0-9a-f]{64}$'),
    attachment_filename TEXT NULL
        CHECK (attachment_filename IS NULL OR char_length(attachment_filename) <= 255),
    UNIQUE (purchase_order_id, previous_version),
    CHECK ((attachment_version IS NULL) = (attachment_sha256 IS NULL)),
    CHECK ((attachment_version IS NULL) = (attachment_filename IS NULL)),
    CHECK (discount_minor <= subtotal_minor),
    CHECK (grand_total_minor = subtotal_minor - discount_minor + ppn_minor + adjustment_minor)
);

CREATE INDEX IF NOT EXISTS purchase_order_corrections_org_history_idx
    ON {{schema}}.purchase_order_corrections (
        org_id, purchase_order_id, previous_version DESC);

CREATE TABLE IF NOT EXISTS {{schema}}.purchase_order_correction_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correction_id BIGINT NOT NULL
        REFERENCES {{schema}}.purchase_order_corrections(id) ON DELETE CASCADE,
    line_number INTEGER NOT NULL CHECK (line_number > 0),
    description TEXT NOT NULL DEFAULT '',
    quotation_item_no INTEGER NULL CHECK (quotation_item_no > 0),
    quotation_sub_no INTEGER NULL CHECK (quotation_sub_no > 0),
    quantity_scaled BIGINT NOT NULL CHECK (quantity_scaled > 0),
    uom TEXT NOT NULL DEFAULT '',
    unit_price_minor BIGINT NOT NULL CHECK (unit_price_minor >= 0),
    discount_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    discount_percent SMALLINT NOT NULL DEFAULT 0
        CHECK (discount_percent BETWEEN 0 AND 100),
    gross_minor BIGINT NOT NULL CHECK (gross_minor >= 0),
    discount_minor BIGINT NOT NULL CHECK (discount_minor >= 0),
    net_minor BIGINT NOT NULL CHECK (net_minor >= 0),
    UNIQUE (correction_id, line_number),
    CHECK (net_minor = gross_minor - discount_minor),
    CHECK (discount_minor <= gross_minor),
    CHECK (quotation_sub_no IS NULL OR quotation_item_no IS NOT NULL)
);

-- A snapshot is evidence. No writer may rewrite it; only the purchase order's
-- own deletion removes it, through ON DELETE CASCADE.
CREATE OR REPLACE FUNCTION {{schema}}.purchase_order_corrections_immutable()
RETURNS trigger
LANGUAGE plpgsql
AS $correction_guard$
BEGIN
    RAISE EXCEPTION
        'purchase order correction % is immutable; record a new correction instead',
        OLD.id
        USING ERRCODE = '23514';
END;
$correction_guard$;

DROP TRIGGER IF EXISTS purchase_order_corrections_immutable_trigger
    ON {{schema}}.purchase_order_corrections;
CREATE TRIGGER purchase_order_corrections_immutable_trigger
    BEFORE UPDATE ON {{schema}}.purchase_order_corrections
    FOR EACH ROW
    EXECUTE FUNCTION {{schema}}.purchase_order_corrections_immutable();

DROP TRIGGER IF EXISTS purchase_order_correction_items_immutable_trigger
    ON {{schema}}.purchase_order_correction_items;
CREATE TRIGGER purchase_order_correction_items_immutable_trigger
    BEFORE UPDATE ON {{schema}}.purchase_order_correction_items
    FOR EACH ROW
    EXECUTE FUNCTION {{schema}}.purchase_order_corrections_immutable();

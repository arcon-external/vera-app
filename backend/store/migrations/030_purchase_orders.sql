-- 030_purchase_orders: manual customer Purchase Order drafts (issue #468).
--
-- A PO is born from one exact issued Quotation revision and belongs to the
-- thin organization boundary established by 029. This migration stores the
-- draft surface only: the header snapshot, the entered lines, and the
-- one-active-record rule. Pricing, discounts, differences, confirmation
-- numbers and attachments arrive in later slices and are deliberately absent.
--
-- The customer/company-facing values are snapshots. Editing a client or a
-- company profile later must never rewrite a PO that was already entered.
CREATE TABLE IF NOT EXISTS {{schema}}.purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    org_id UUID NOT NULL REFERENCES {{schema}}.organizations(id),
    quotation_id BIGINT NOT NULL REFERENCES {{schema}}.quotations(id),
    -- The exact issued revision the PO follows. Immutable.
    source_revision SMALLINT NOT NULL CHECK (source_revision >= 0),
    -- draft = entry in progress, saved = finalized (#471). Only draft may be
    -- edited; the state is stored rather than derived so a future final save
    -- can set it in the same transaction as the differences.
    state TEXT NOT NULL DEFAULT 'draft' CHECK (state IN ('draft', 'saved')),
    customer_id BIGINT NOT NULL REFERENCES {{schema}}.customers(id),
    -- Snapshots copied from the selected revision at creation.
    customer_name TEXT NOT NULL,
    billing_address TEXT NOT NULL DEFAULT '',
    delivery_address TEXT NOT NULL DEFAULT '',
    ship_to_code TEXT NOT NULL DEFAULT '',
    contact_email TEXT NOT NULL DEFAULT '',
    contact_phone TEXT NOT NULL DEFAULT '',
    -- Customer PO identity is optional while drafting; uniqueness per
    -- customer is a final-save rule (#471), not a draft rule.
    po_number TEXT NULL,
    po_date DATE NULL,
    received_date DATE NOT NULL,
    requested_delivery_date DATE NULL,
    payment_terms_days SMALLINT NOT NULL DEFAULT 0
        CHECK (payment_terms_days BETWEEN 0 AND 3650),
    incoterms TEXT NOT NULL DEFAULT '',
    currency TEXT NOT NULL,
    tax_zone TEXT NOT NULL,
    tax_category TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by BIGINT NOT NULL REFERENCES {{schema}}.users(id),
    updated_by BIGINT NOT NULL REFERENCES {{schema}}.users(id)
);

-- One active record per Quotation, across every revision. Drafts count:
-- two people must not create competing records for the same source (stories
-- 11-12). Deletion columns arrive with #480; until then this index is the
-- whole uniqueness story.
CREATE UNIQUE INDEX IF NOT EXISTS purchase_orders_active_quotation_idx
    ON {{schema}}.purchase_orders (quotation_id);

-- Every store query is organization-scoped; this keeps the tenant filter
-- indexed even when a future list grows.
CREATE INDEX IF NOT EXISTS purchase_orders_org_idx
    ON {{schema}}.purchase_orders (org_id, id);

CREATE TABLE IF NOT EXISTS {{schema}}.purchase_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT NOT NULL
        REFERENCES {{schema}}.purchase_orders(id) ON DELETE CASCADE,
    -- The customer's own line order. Stable within one PO.
    line_number INTEGER NOT NULL CHECK (line_number > 0),
    description TEXT NOT NULL DEFAULT '',
    -- The matched Quotation line, by number within the frozen source
    -- revision. Nullable because an extra line is allowed (stories 39-41).
    -- Numbers, not row ids, so a deleted Quotation cannot cascade these away.
    quotation_item_no INTEGER NULL CHECK (quotation_item_no > 0),
    quotation_sub_no INTEGER NULL CHECK (quotation_sub_no > 0),
    -- Quantity with four decimal places, stored as an exact scaled integer
    -- (10^4). Never a float and never a decimal string that parses
    -- differently in another locale.
    quantity_scaled BIGINT NOT NULL CHECK (quantity_scaled > 0),
    uom TEXT NOT NULL DEFAULT '',
    -- Currency minor units of the PO's currency.
    unit_price_minor BIGINT NOT NULL CHECK (unit_price_minor >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (purchase_order_id, line_number),
    CHECK (quotation_sub_no IS NULL OR quotation_item_no IS NOT NULL)
);
